const rectangle = (x: number, z: number, w: number, d: number): Point2[] => [
  [x, z],
  [x + w, z],
  [x + w, z + d],
  [x, z + d],
];

/** Buffer a short schematic centreline; vertices remain canonical in both views. */
function passage(points: Point2[], width: number): Point2[] {
  const left: Point2[] = [];
  const right: Point2[] = [];
  points.forEach(([x, z], i) => {
    const before = points[Math.max(0, i - 1)];
    const after = points[Math.min(points.length - 1, i + 1)];
    const dx = after[0] - before[0];
    const dz = after[1] - before[1];
    const length = Math.hypot(dx, dz) || 1;
    left.push([
      x - ((dz / length) * width) / 2,
      z + ((dx / length) * width) / 2,
    ]);
    right.push([
      x + ((dz / length) * width) / 2,
      z - ((dx / length) * width) / 2,
    ]);
  });
  return [...left, ...right.reverse()];
}

